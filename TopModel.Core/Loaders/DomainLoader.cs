using System.Globalization;
using TopModel.Core.FileModel;
using TopModel.Core.Model;
using TopModel.Core.Model.Implementation;
using YamlDotNet.Core;
using YamlDotNet.Core.Events;

namespace TopModel.Core.Loaders;

public class DomainLoader(FileChecker fileChecker) : ILoader
{
    /// <inheritdoc cref="ILoader.Load" />
    public void Load(Parser parser, ModelFile modelFile, Reference location)
    {
        var domain = new Domain() { ModelFile = modelFile, Location = location };
        modelFile.Domains.Add(domain);
        parser.ConsumeMapping(prop =>
        {
            parser.TryConsume<Scalar>(out var value);

            switch (prop.Value)
            {
                case "name":
                    domain.Name = new LocatedString(value!);
                    break;
                case "label":
                    domain.Label = value!.Value;
                    break;
                case "length":
                    domain.Length = Convert.ToInt32(decimal.Parse(value!.Value, CultureInfo.InvariantCulture));
                    break;
                case "scale":
                    domain.Scale = Convert.ToInt32(decimal.Parse(value!.Value, CultureInfo.InvariantCulture));
                    break;
                case "autoGeneratedValue":
                    domain.AutoGeneratedValue = value!.Value == "true";
                    break;
                case "bodyParam":
                    domain.BodyParam = value!.Value == "true";
                    break;
                case "asDomains":
                    parser.ConsumeMapping(prop =>
                    {
                        domain.AsDomainReferences[prop.Value] = new DomainReference(parser.Consume<Scalar>());
                    });
                    break;
                case "mediaType":
                    domain.MediaType = value!.Value;
                    break;
                case "parameters":
                    domain.TemplateParameters = fileChecker.Deserialize<IList<TemplateParameter>>(parser);
                    foreach (var param in domain.TemplateParameters)
                    {
                        param.Domain = domain;
                    }

                    break;
                case "annotations":
                    parser.ConsumeSequence(() =>
                    {
                        if (parser.Current is MappingStart)
                        {
                            parser.ConsumeMapping(prop =>
                            {
                                var annotation = new AnnotationReference(prop)
                                {
                                    ParameterReferences = fileChecker.Deserialize<
                                        Dictionary<ParameterReference, StringWithVariables>
                                    >(parser),
                                };

                                domain.AnnotationReferences.Add(annotation);
                            });
                        }
                        else
                        {
                            domain.AnnotationReferences.Add(new AnnotationReference(parser.Consume<Scalar>()));
                        }
                    });
                    break;
                case "excludedAnnotations":
                    parser.ConsumeSequence(() =>
                    {
                        domain.ExcludedAnnotationReferences.Add(new AnnotationReference(parser.Consume<Scalar>()));
                    });
                    break;
                default:
                    var implementation = new DomainImplementation();

                    parser.ConsumeMapping(prop =>
                    {
                        switch (prop.Value)
                        {
                            case "type":
                                implementation.Type = new(parser.Consume<Scalar>());
                                break;
                            case "genericType":
                                implementation.GenericType = new(parser.Consume<Scalar>());
                                break;
                            case "imports":
                                implementation.Imports = fileChecker.Deserialize<List<StringWithVariables>>(parser);
                                break;
                            case "values":
                                ValueTemplate HandleValueTemplate()
                                {
                                    var valueTemplate = new ValueTemplate();

                                    if (parser.Current is MappingStart)
                                    {
                                        parser.ConsumeMapping(prop =>
                                        {
                                            switch (prop.Value)
                                            {
                                                case "value":
                                                    valueTemplate.Value = new(parser.Consume<Scalar>());
                                                    break;
                                                case "imports":
                                                    parser.ConsumeSequence(() =>
                                                        valueTemplate.Imports.Add(new(parser.Consume<Scalar>()))
                                                    );
                                                    break;
                                            }
                                        });
                                    }
                                    else
                                    {
                                        valueTemplate.Value = new(parser.Consume<Scalar>());
                                    }

                                    return valueTemplate;
                                }

                                parser.ConsumeMapping(prop =>
                                {
                                    switch (prop.Value)
                                    {
                                        case "template":
                                            implementation.ValueTemplates.Add(
                                                ValueTemplate.Default,
                                                HandleValueTemplate()
                                            );
                                            break;
                                        case "overrides":
                                            parser.ConsumeMapping(prop =>
                                                implementation.ValueTemplates.Add(prop.Value, HandleValueTemplate())
                                            );
                                            break;
                                    }
                                });
                                break;
                        }
                    });

                    domain.Implementations[prop.Value] = implementation;
                    break;
            }
        });
    }
}
